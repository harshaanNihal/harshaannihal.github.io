#!/bin/sh
# Refresh _data/github.yml from the GitHub API. Needs the gh CLI, logged in.
# Run it, review the diff, commit. The site reads these numbers at build time.
set -eu

user=harshaanNihal
project=saeloun/miru-web
cd "$(dirname "$0")/.."

search_count() {
  gh api -X GET search/issues -f q="$1" -f per_page=1 --jq .total_count
}

{
  echo "# Generated by tools/update-github-data.sh. Edit _data/profile.yml instead."
  gh api "users/$user" --jq '"public_repos: \(.public_repos)\nfollowers: \(.followers)\njoined: \(.created_at[0:4])"'
  echo "merged_prs_elsewhere: $(search_count "author:$user is:pr is:merged is:public -user:$user")"
  echo "miru_prs: $(search_count "author:$user is:pr is:merged repo:$project")"
  echo "miru_stars: $(gh api "repos/$project" --jq .stargazers_count)"
  echo "updated: $(date -u +%Y-%m-%d)"
} > _data/github.yml.tmp
mv _data/github.yml.tmp _data/github.yml
cat _data/github.yml
