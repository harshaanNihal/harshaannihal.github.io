// Copies the code shown in the Code section's experiments out of the real source files, so it never drifts:
//   node tools/excerpts.mjs
// Each excerpt starts at the first line matching `from` and runs to the `blocks`-th line after it that matches
// `to`. It is written, dedented and wrapped in raw tags, to _includes/excerpts/NAME.txt, and its file and line
// range to _data/excerpts.yml for the file view's header. Run it after changing any of the excerpted code.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

const excerpts = [
  { name: 'painted-sky', file: 'tools/painted-sky.mjs', from: /^\/\* The river of dabs/, to: /^}$/ },
  { name: 'constellation', file: '_includes/site.js', from: /^ {4}function step\(dt\) \{$/, to: /^ {4}}$/ },
  { name: 'notch', file: '_includes/site.css', from: /^\.btn--notch \{$/, to: /^}$/, blocks: 3 },
  { name: 'skills-sky', file: '_includes/site.css', from: /^\.skill-sky__star,$/, to: /^}$/, blocks: 2 }
];

mkdirSync(`${root}_includes/excerpts`, { recursive: true });
const data = ['# Generated by tools/excerpts.mjs: where each excerpt in _includes/excerpts/ comes from. Don\'t edit.'];
for (const { name, file, from, to, blocks = 1 } of excerpts) {
  const lines = readFileSync(`${root}${file}`, 'utf8').split('\n');
  const start = lines.findIndex((line) => from.test(line));
  if (start < 0) throw new Error(`${name}: no line in ${file} matches ${from}`);
  let end = start;
  for (let found = 0; found < blocks; end++) {
    if (end >= lines.length) throw new Error(`${name}: ran off the end of ${file}`);
    if (to.test(lines[end]) && end > start) found++;
    if (found === blocks) break;
  }
  const body = lines.slice(start, end + 1);
  const indent = Math.min(...body.filter((line) => line.trim()).map((line) => line.match(/^ */)[0].length));
  const code = body.map((line) => line.slice(indent)).join('\n');
  writeFileSync(`${root}_includes/excerpts/${name}.txt`, `{% raw %}\n${code}\n{% endraw %}\n`);
  data.push(`${name}: { file: "${file}", from: ${start + 1}, to: ${end + 1} }`);
  console.log(`${name}: ${file} lines ${start + 1}-${end + 1}`);
}
writeFileSync(`${root}_data/excerpts.yml`, data.join('\n') + '\n');
